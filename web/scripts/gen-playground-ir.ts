/**
 * Generates the static IR fallback for the playground's built-in examples.
 *
 * The playground's live runner only exists in `vite dev`, so the deployed
 * site needs a fallback. This script runs the real frontend over each
 * built-in example and writes the result, so the page shows the exact IR
 * the engine would emit rather than a mock.
 *
 * Run: bun scripts/gen-playground-ir.ts
 */
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"

import { PLAYGROUND_EXAMPLES } from "../apps/web/src/lib/playground-examples"
import { requireUv, runTool } from "./toolchain"

const WEB_ROOT = resolve(
  dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")),
  "..",
)
const REPO_ROOT = resolve(WEB_ROOT, "..")
const FRONTEND = join(REPO_ROOT, "src", "frontend", "frontend.py")
const CACHE_DIR = join(WEB_ROOT, "node_modules", ".cache")

export function hash(source: string) {
  // FNV-1a, matching irKey() in apps/web/src/docs/templates.tsx
  let h = 0x811c9dc5
  for (let i = 0; i < source.length; i++) {
    h ^= source.charCodeAt(i)
    h = Math.imul(h, 0x01000193) >>> 0
  }
  return h.toString(16).padStart(8, "0")
}

/**
 * Normalises the frontend's output to LF, with no trailing blank lines.
 *
 * The frontend emits its IR with the platform's line ending, so the same
 * program produces CRLF on Windows and LF on Linux. The generated file has
 * to be byte-identical on every platform.
 */
export function normalise(text: string): string {
  return text
    .replace(/\r\n/g, "\n")
    .split("\n")
    .map((line) => line.trimEnd())
    .filter((line) => line.length > 0)
    .join("\n")
}

const UV = requireUv()
const out: Record<string, string> = {}
const failed: string[] = []

mkdirSync(CACHE_DIR, { recursive: true })

for (const example of PLAYGROUND_EXAMPLES) {
  const file = join(CACHE_DIR, `playground-${example.id}.lio`)
  writeFileSync(file, example.source, "utf8")
  const res = runTool(UV, [FRONTEND, file], REPO_ROOT)
  const text = normalise(res.out)
  if (res.code === 0 && text) {
    out[hash(example.source)] = text
  } else {
    failed.push(`${example.id}: ${res.err.trim().split("\n").pop()}`)
  }
}

const target = join(WEB_ROOT, "apps", "web", "src", "lib")
writeFileSync(
  join(target, "playground-ir.ts"),
  `/**
 * The pre-generated IR for the playground's built-in examples.
 *
 * The playground's live runner is a dev-only Vite middleware, so a visitor
 * to the deployed site cannot run a program there. These IR blobs are the
 * real frontend output for the eight built-in examples, generated by
 * \`scripts/gen-playground-ir.ts\`, so the page still shows something true in
 * production: the exact IR the engine would emit.
 *
 * Keyed by the FNV-1a hash of the example source, matching \`irKey()\` in
 * \`docs/templates.tsx\`.
 */
export const PLAYGROUND_IR: Record<string, string> = ${JSON.stringify(out, null, 2)}
`,
  "utf8",
)

console.log(
  `wrote ${Object.keys(out).length} playground IR blobs to apps/web/src/lib/playground-ir.ts`,
)
for (const f of failed) console.log(`  refused: ${f}`)
